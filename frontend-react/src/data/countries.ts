/** iso2 (minuscule) epingles en tete du selecteur : Maroc + Maghreb + France. */
export const PINNED_COUNTRY_ISO2: string[] = ['ma', 'dz', 'tn', 'fr'];

const collator = new Intl.Collator('fr', { sensitivity: 'base' });

/**
 * Pays tries pour l'affichage du selecteur : d'abord les pays epingles
 * ({@link PINNED_COUNTRY_ISO2}, dans cet ordre), puis tous les autres par ordre
 * alphabetique francais.
 */
export const sortedCountries: Country[] = (() => {
  const pinned = PINNED_COUNTRY_ISO2
    .map((iso2) => COUNTRIES.find((c) => c.iso2 === iso2))
    .filter((c): c is Country => Boolean(c));
  const pinnedSet = new Set(pinned.map((c) => c.iso2));
  const rest = COUNTRIES
    .filter((c) => !pinnedSet.has(c.iso2))
    .sort((a, b) => collator.compare(a.name, b.name));
  return [...pinned, ...rest];
})();

/** Retrouve un pays par son iso2 (insensible a la casse). */
export function countryByIso2(iso2: string | null | undefined): Country | undefined {
  if (!iso2) return undefined;
  const lower = iso2.toLowerCase();
  return COUNTRIES.find((c) => c.iso2 === lower);
}

